        <h1 class="font-serif text-5xl font-semibold">Sobre nosotros</h1>
        <div class="prose-content mt-8 max-w-[72ch] text-lg">
            <p>Gaining Grades nació como un proyecto en la Universidad Vasco de Quiroga. La plataforma de cursos que usábamos era deficiente, y quisimos averiguar qué tan complicado era construir una mejor: más clara para quien aprende, más sencilla para quien enseña y cuidadosa con los datos de todos.</p>
            <p>Hoy es una plataforma para dar y recibir clases en línea, pensada para ponentes independientes, escuelas y personas que aprenden por su cuenta.</p>
            <h2>Misión <span class="text-base font-normal text-muted">(provisional)</span></h2>
            <p>Que armar un curso y seguirlo sea tan sencillo que el tiempo se vaya en enseñar y aprender, no en pelear con la herramienta.</p>
            <h2>Equipo <span class="text-base font-normal text-muted">(provisional)</span></h2>
            <p>Esta sección se completará con las personas que forman el proyecto.</p>
